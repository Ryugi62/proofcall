"""Regenerate the README results block from runs/*/results.json (numbers are never typed by hand)."""
from __future__ import annotations

import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN, END = "<!-- RESULTS:BEGIN", "<!-- RESULTS:END -->"


def block(results_paths):
    lines = []
    for p in results_paths:
        s = json.load(open(p, encoding="utf-8"))["summary"]
        run = os.path.basename(os.path.dirname(p))
        lines += [f"**Run `{run}`** — [report](runs/{run}/report.md)", "",
                  "| mode | calls | agent turns | violations | turns with a violation (95% CI) | blocked before speaking | outcome match | task success (95% CI) | median / p90 model ms | median audit ms |",
                  "|---|---|---|---|---|---|---|---|---|---|"]
        for mode, m in s.items():
            if mode == "comparison":
                continue
            lines.append(f"| {mode} | {m['calls']} | {m['agent_turns']} | {m['violations']} | "
                         f"{m['turns_with_violation']} {m['turn_violation_ci95']} | {m['blocked_turns']} | "
                         f"{m['outcome_match']}/{m['calls']} | {m['task_success']}/{m['calls']} {m['task_success_ci95']} | "
                         f"{m['median_model_ms']} / {m['p90_model_ms']} | {m['median_audit_ms']} |")
        if "comparison" in s:
            c = s["comparison"]
            lines.append(f"\nCalls with ≥1 violation, baseline vs guarded: Fisher exact p = {c['calls_with_violation_fisher_p']} "
                         f"(call level). Task success: p = {c['task_success_fisher_p']}.")
        lines.append("")
    return "\n".join(lines)


def render(readme: str, results_paths) -> str:
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    head = BEGIN + " (generated by scripts/update_readme.py from runs/*/results.json — do not edit by hand) -->"
    return pat.sub(lambda m: head + "\n" + block(results_paths) + "\n" + END, readme)


def main() -> int:
    paths = sorted(p for p in glob.glob(os.path.join(ROOT, "runs", "*", "results.json")) if not any(x in p for x in ("aborted", "smoke", "pilot")))
    rp = os.path.join(ROOT, "README.md")
    new = render(open(rp, encoding="utf-8").read(), paths)
    if "--check" in sys.argv:
        return 0 if new == open(rp, encoding="utf-8").read() else 1
    open(rp, "w", encoding="utf-8").write(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
